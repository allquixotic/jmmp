import { mkdir, writeFile, copyFile } from "node:fs/promises";
import { join } from "node:path";
import { build } from "esbuild";
const root = join(import.meta.dir, "..");
const target = process.argv[2];
const compiler = Bun.spawnSync(["rustc", "-vV"]);
const host = compiler.stdout.toString().match(/^host: (.+)$/m)?.[1];
const cargoTarget = target && target !== host ? target : undefined;
const args = ["cargo", "build", "--release", "--locked", "--manifest-path", join(root, "native/Cargo.toml")];
if (cargoTarget) args.push("--target", cargoTarget);
const result = Bun.spawn(args, { cwd: root, stdout: "inherit", stderr: "inherit" });
if (await result.exited) throw new Error("Rust helper build failed (install Rust >= 1.95 and the target toolchain)");
const helper = join(root, "native/target", ...(cargoTarget ? [cargoTarget] : []), "release/jmmp-moq");
// Decoder packages assign names to their worker exports during initialization.
// Bun's DCE currently drops those classes but retains the assignments. Keep all
// decoder exports with esbuild; the result is still one Bun worker module.
const worker = await build({ entryPoints: [join(root, "server/src/audio/worker.ts")], bundle: true,
  platform: "node", target: "es2023", format: "esm", external: ["bun:sqlite"],
  minify: false, keepNames: true, treeShaking: false, write: false });
const code = worker.outputFiles![0]!.text;
const base64 = Buffer.from(await Bun.file(helper).arrayBuffer()).toString("base64");
await writeFile(join(root, "server/src/audio/assets.ts"), `// Generated by build/native.ts.\nexport const helperBase64 = ${JSON.stringify(base64)};\nexport const workerSource = ${JSON.stringify(code)};\n`);
await mkdir(join(root, "dist"), { recursive: true });
await copyFile(helper, join(root, "dist", target ? `jmmp-moq-${target}` : "jmmp-moq"));
console.log("Built and embedded jmmp Opus/MoQ helper and Bun audio worker");
