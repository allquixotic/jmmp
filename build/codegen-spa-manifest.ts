// Generates server/src/spa-manifest.ts: a map of paths → base64 file contents.
// This lets `bun build --compile` embed the entire SPA into the binary so the
// distributed jmmp executable is fully self-contained.

import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";

const SPA_CANDIDATES = [
  join(import.meta.dir, "..", "client", "dist", "pwa"),
  join(import.meta.dir, "..", "client", "dist", "spa"),
];
const SRC = SPA_CANDIDATES.find((p) => {
  try {
    statSync(p);
    return true;
  } catch {
    return false;
  }
});
const OUT = join(import.meta.dir, "..", "server", "src", "spa-manifest.ts");

if (!SRC) {
  console.error("No client build found. Run client build first.");
  process.exit(1);
}

interface Entry {
  path: string;
  bytes: Uint8Array;
}

function walk(dir: string, base: string, out: Entry[]): void {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const rel = posix.join(base, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      walk(full, rel, out);
    } else {
      out.push({ path: rel, bytes: readFileSync(full) });
    }
  }
}

const entries: Entry[] = [];
walk(SRC, "", entries);

const lines: string[] = [];
lines.push("// Copyright 2026 Sean McNamara");
lines.push("// SPDX-License-Identifier: Apache-2.0");
lines.push("");
lines.push("// AUTO-GENERATED by build/codegen-spa-manifest.ts. Do not edit by hand.");
lines.push("// Each value is a base64-encoded copy of the bundled client asset.");
lines.push("");
lines.push("export const SPA_FILES: Record<string, string> = {");
for (const e of entries.sort((a, b) => a.path.localeCompare(b.path))) {
  const b64 = Buffer.from(e.bytes).toString("base64");
  lines.push(`  ${JSON.stringify(e.path)}: "${b64}",`);
}
lines.push("};");
lines.push("");

writeFileSync(OUT, lines.join("\n"));
console.log(`Wrote ${OUT} with ${entries.length} files (${(lines.join("\n").length / 1024).toFixed(0)} KB).`);
